/**
 * Smart Microgrid - Contract Deployment Script
 * 
 * This script deploys the EnergyTrading contract to the specified network
 * and saves the contract address and ABI for the backend server.
 */

const hre = require("hardhat");
const fs = require("fs");
const path = require("path");

async function main() {
    console.log("\n" + "=".repeat(60));
    console.log("Smart Microgrid - Blockchain Deployment");
    console.log("=".repeat(60) + "\n");

    // Get network info
    const network = hre.network.name;
    console.log(`📡 Deploying to network: ${network}`);

    // Get deployer account
    const [deployer] = await hre.ethers.getSigners();
    console.log(`👤 Deployer address: ${deployer.address}`);

    const balance = await hre.ethers.provider.getBalance(deployer.address);
    console.log(`💰 Deployer balance: ${hre.ethers.formatEther(balance)} ETH\n`);

    // Deploy the contract
    console.log("🚀 Deploying EnergyTrading contract...");

    const EnergyTrading = await hre.ethers.getContractFactory("EnergyTrading");
    const energyTrading = await EnergyTrading.deploy();

    await energyTrading.waitForDeployment();

    const contractAddress = await energyTrading.getAddress();

    console.log(`✅ Contract deployed successfully!`);
    console.log(`📍 Contract Address: ${contractAddress}\n`);

    // Get contract info
    const owner = await energyTrading.owner();
    const pricePerKwh = await energyTrading.defaultPricePerKwh();

    console.log(`👑 Contract Owner: ${owner}`);
    console.log(`💵 Price per kWh: ${hre.ethers.formatEther(pricePerKwh)} ETH\n`);

    // Save deployment info for backend
    const deploymentInfo = {
        network: network,
        contractAddress: contractAddress,
        deployerAddress: deployer.address,
        deployedAt: new Date().toISOString(),
        blockNumber: await hre.ethers.provider.getBlockNumber()
    };

    // Create deployment directory
    const deploymentDir = path.join(__dirname, "..", "deployments");
    if (!fs.existsSync(deploymentDir)) {
        fs.mkdirSync(deploymentDir, { recursive: true });
    }

    // Save deployment info
    const deploymentPath = path.join(deploymentDir, `${network}.json`);
    fs.writeFileSync(deploymentPath, JSON.stringify(deploymentInfo, null, 2));
    console.log(`📁 Deployment info saved to: ${deploymentPath}`);

    // Copy ABI to backend
    const artifactsPath = path.join(__dirname, "..", "artifacts", "contracts", "EnergyTrading.sol", "EnergyTrading.json");
    const backendAbiPath = path.join(__dirname, "..", "..", "backend", "contracts", "EnergyTrading.json");

    // Ensure backend contracts directory exists
    const backendContractsDir = path.dirname(backendAbiPath);
    if (!fs.existsSync(backendContractsDir)) {
        fs.mkdirSync(backendContractsDir, { recursive: true });
    }

    // Copy full artifact (includes ABI)
    if (fs.existsSync(artifactsPath)) {
        const artifact = JSON.parse(fs.readFileSync(artifactsPath, "utf8"));

        // Save simplified version for backend
        const backendArtifact = {
            contractName: artifact.contractName,
            abi: artifact.abi,
            address: contractAddress,
            network: network,
            deployedAt: deploymentInfo.deployedAt
        };

        fs.writeFileSync(backendAbiPath, JSON.stringify(backendArtifact, null, 2));
        console.log(`📄 Contract ABI copied to backend: ${backendAbiPath}`);
    }

    // Create/update backend .env file with contract address
    const envPath = path.join(__dirname, "..", "..", "backend", ".env");
    const envContent = `# Smart Microgrid Backend Configuration
# Generated by deployment script on ${new Date().toISOString()}

# Blockchain Configuration
GANACHE_URL=http://127.0.0.1:7545
CONTRACT_ADDRESS=${contractAddress}
DEPLOYER_PRIVATE_KEY=0x4f3edf983ac636a65a842ce7c78d9aa706d3b113bce9c46f30d7d21715b23b1d

# Server Configuration
PORT=3000
NODE_ENV=development

# House Addresses (from Ganache)
HOUSE_A_ADDRESS=0x1111111111111111111111111111111111111111
HOUSE_B_ADDRESS=0x2222222222222222222222222222222222222222
`;

    fs.writeFileSync(envPath, envContent);
    console.log(`⚙️  Backend .env file created: ${envPath}`);

    console.log("\n" + "=".repeat(60));
    console.log("✅ Deployment Complete!");
    console.log("=".repeat(60));
    console.log("\nNext steps:");
    console.log("1. cd ../backend");
    console.log("2. npm install");
    console.log("3. npm start");
    console.log("=".repeat(60) + "\n");
}

main()
    .then(() => process.exit(0))
    .catch((error) => {
        console.error("❌ Deployment failed:");
        console.error(error);
        process.exit(1);
    });

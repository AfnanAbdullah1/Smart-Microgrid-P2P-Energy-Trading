import os, json, pickle, warnings, sys
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use('Agg')      # Non-interactive backend (no GUI needed)
import matplotlib.pyplot as plt
from sklearn.preprocessing import MinMaxScaler
from sklearn.metrics import mean_absolute_error, mean_squared_error
warnings.filterwarnings('ignore')

# ── Check TensorFlow availability ────────────────────────────────
try:
    import tensorflow as tf
    from tensorflow.keras.models import Sequential
    from tensorflow.keras.layers import (
        LSTM, Dense, Dropout, BatchNormalization, Bidirectional
    )
    from tensorflow.keras.callbacks import (
        EarlyStopping, ModelCheckpoint, ReduceLROnPlateau
    )
    print(f"✓ TensorFlow {tf.__version__} loaded")
except ImportError:
    print("✗ TensorFlow not installed.  Run:  pip install tensorflow")
    sys.exit(1)


# ==================== CONFIGURATION ====================

CSV_FILE        = os.path.join('..', 'backend', 'data', 'sensor_log.csv')
MODEL_DIR       = 'models'
MODEL_FILE      = os.path.join(MODEL_DIR, 'best_model.keras')
SCALER_FILE     = os.path.join(MODEL_DIR, 'scaler.pkl')
METADATA_FILE   = os.path.join(MODEL_DIR, 'model_metadata.json')

# ── Data settings ───────────────────────────────────────────────
SMOOTH_WINDOW   = 5           # Rolling average for PZEM noise
SEQUENCE_LENGTH = 20          # 20 rows × 0.5s = 10 seconds of history
TRAIN_RATIO     = 0.70
VAL_RATIO       = 0.15        # remaining 15% → test

# ── Prediction horizons (in number of rows at 0.5s interval) ────
HORIZONS = {
    '1min':  120,    # 60s ÷ 0.5s = 120 rows ahead
    '5min':  600,    # 300s ÷ 0.5s
    '10min': 1200,   # 600s ÷ 0.5s
}
PRIMARY_HORIZON = '1min'      # main target for the LSTM

# ── Model settings ──────────────────────────────────────────────
EPOCHS          = 80
BATCH_SIZE      = 128
LSTM_UNITS_1    = 128
LSTM_UNITS_2    = 64

# Target column we are predicting
TARGET_COL      = 'houseA_power'

# Feature columns fed to the model
FEATURE_COLS = [
    'houseA_voltage', 'houseA_current', 'houseA_power',
    'houseA_frequency', 'houseA_pf',
    'houseB_power', 'houseB_current',
    'relay_state', 'receiving_from_A',
    'hour', 'day_of_week'
]


# ==================== DATA LOADING ====================

def load_csv():
    print(f"\nLoading data from: {CSV_FILE}")
    if not os.path.exists(CSV_FILE):
        print("⚠  sensor_log.csv not found.")
        print("   Run:  python generate_data.py   to create synthetic data")
        print("   Or start your hardware system and let it collect data.")
        return None

    df = pd.read_csv(CSV_FILE, parse_dates=['timestamp'])
    df = df.sort_values('timestamp').reset_index(drop=True)
    print(f"✓ Loaded {len(df):,} rows  |  "
          f"{df['timestamp'].min()} → {df['timestamp'].max()}")
    return df


# ==================== PREPROCESSING ====================

def remove_outliers(df):
    """IQR-based outlier removal on power columns."""
    power_cols = ['houseA_power', 'houseB_power']
    before = len(df)
    for col in power_cols:
        if col not in df.columns:
            continue
        Q1, Q3 = df[col].quantile([0.25, 0.75])
        IQR = Q3 - Q1
        df = df[(df[col] >= Q1 - 3*IQR) & (df[col] <= Q3 + 3*IQR)]
    print(f"✓ Outlier removal: {before:,} → {len(df):,} rows  "
          f"({before - len(df)} removed)")
    return df.reset_index(drop=True)


def smooth_sensor_noise(df, window=SMOOTH_WINDOW):
    """Rolling average on noisy PZEM columns."""
    noisy_cols = [
        'houseA_voltage', 'houseA_current', 'houseA_power',
        'houseA_frequency', 'houseA_pf',
        'houseB_voltage', 'houseB_current', 'houseB_power'
    ]
    for col in noisy_cols:
        if col in df.columns:
            df[col] = df[col].rolling(window, min_periods=1).mean()
    print(f"✓ Applied rolling-average smoothing (window={window})")
    return df


def preprocess(df):
    """Validate and select feature columns."""
    missing = [c for c in FEATURE_COLS if c not in df.columns]
    if missing:
        print(f"⚠  Missing columns: {missing}")
        return None

    df = df[FEATURE_COLS].copy()
    df = df.ffill().bfill()

    MIN_ROWS = SEQUENCE_LENGTH * 10
    if len(df) < MIN_ROWS:
        print(f"\n⚠  Only {len(df)} rows available. Need at least {MIN_ROWS}.")
        return None

    print(f"✓ Preprocessed shape: {df.shape}")
    return df


# ==================== SEQUENCE CREATION ====================

def make_sequences(scaled, target_idx, seq_len, horizon_rows=1):
    """
    X: [seq_len, n_features]
    y: value of TARGET_COL  `horizon_rows` steps ahead.
    """
    X, y = [], []
    limit = len(scaled) - seq_len - horizon_rows
    for i in range(limit):
        X.append(scaled[i : i + seq_len])
        y.append(scaled[i + seq_len + horizon_rows - 1, target_idx])
    return np.array(X, dtype=np.float32), np.array(y, dtype=np.float32)


# ==================== MODEL ====================

def build_model(seq_len, n_features):
    model = Sequential([
        Bidirectional(
            LSTM(LSTM_UNITS_1, return_sequences=True),
            input_shape=(seq_len, n_features)
        ),
        BatchNormalization(),
        Dropout(0.25),

        LSTM(LSTM_UNITS_2, return_sequences=False),
        BatchNormalization(),
        Dropout(0.25),

        Dense(64, activation='relu'),
        Dense(32, activation='relu'),
        Dense(1)
    ])
    model.compile(optimizer='adam', loss='mse', metrics=['mae'])
    print("\n✓ Model built:")
    model.summary()
    return model


# ==================== TRAIN ====================

def train(model, X_tr, y_tr, X_val, y_val):
    os.makedirs(MODEL_DIR, exist_ok=True)

    callbacks = [
        EarlyStopping(monitor='val_loss', patience=12,
                      restore_best_weights=True, verbose=1),
        ModelCheckpoint(MODEL_FILE, monitor='val_loss',
                        save_best_only=True, verbose=1),
        ReduceLROnPlateau(monitor='val_loss', factor=0.5,
                          patience=6, min_lr=1e-6, verbose=1),
    ]

    history = model.fit(
        X_tr, y_tr,
        validation_data=(X_val, y_val),
        epochs=EPOCHS,
        batch_size=BATCH_SIZE,
        callbacks=callbacks,
        verbose=1
    )
    return history


# ==================== EVALUATE ====================

def inverse_transform_target(vals, scaler, target_idx, n_features):
    """Convert scaled predictions back to real Watts."""
    dummy = np.zeros((len(vals), n_features))
    dummy[:, target_idx] = vals
    return scaler.inverse_transform(dummy)[:, target_idx]


def evaluate(model, X_test, y_test, scaler, target_idx, n_features):
    y_pred_scaled = model.predict(X_test, verbose=0).flatten()

    y_true_W = inverse_transform_target(y_test, scaler, target_idx, n_features)
    y_pred_W = inverse_transform_target(y_pred_scaled, scaler, target_idx, n_features)

    mae  = mean_absolute_error(y_true_W, y_pred_W)
    rmse = np.sqrt(mean_squared_error(y_true_W, y_pred_W))
    # Avoid division by zero for MAPE
    mask = y_true_W > 0.1
    mape = np.mean(np.abs((y_true_W[mask] - y_pred_W[mask]) / y_true_W[mask])) * 100

    print(f"\n{'='*50}")
    print("  Test Results  (real-scale Watts)")
    print(f"{'='*50}")
    print(f"  MAE  : {mae:.3f} W   ← average error")
    print(f"  RMSE : {rmse:.3f} W")
    print(f"  MAPE : {mape:.2f} %  ← lower is better")
    print(f"{'='*50}")

    return y_true_W, y_pred_W, {'mae': mae, 'rmse': rmse, 'mape': mape}


# ==================== PLOTS ====================

def plot_history(history):
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 5))

    ax1.plot(history.history['loss'],     label='Train Loss', lw=2)
    ax1.plot(history.history['val_loss'], label='Val Loss', lw=2)
    ax1.set_title('Training Loss (MSE)', fontsize=14, fontweight='bold')
    ax1.set_xlabel('Epoch')
    ax1.set_ylabel('Loss')
    ax1.legend()
    ax1.grid(True, alpha=0.3)

    ax2.plot(history.history['mae'],     label='Train MAE', lw=2)
    ax2.plot(history.history['val_mae'], label='Val MAE', lw=2)
    ax2.set_title('Mean Absolute Error', fontsize=14, fontweight='bold')
    ax2.set_xlabel('Epoch')
    ax2.set_ylabel('MAE')
    ax2.legend()
    ax2.grid(True, alpha=0.3)

    plt.tight_layout()
    out = os.path.join(MODEL_DIR, 'training_history.png')
    plt.savefig(out, dpi=150, bbox_inches='tight')
    plt.close()
    print(f"✓ Training history plot → {out}")


def plot_predictions(y_true, y_pred, n=500):
    fig, axes = plt.subplots(2, 1, figsize=(16, 8), gridspec_kw={'height_ratios': [3, 1]})

    # Main prediction plot
    axes[0].plot(y_true[:n], label='Actual (W)', lw=1.5, color='#2196F3')
    axes[0].plot(y_pred[:n], label='Predicted (W)', lw=1.5, alpha=0.85, color='#FF5722')
    axes[0].fill_between(range(n),
                         y_pred[:n] - 0.5, y_pred[:n] + 0.5,
                         alpha=0.15, color='#FF5722', label='±0.5W band')
    axes[0].set_title('House A Power — Actual vs Predicted', fontsize=14, fontweight='bold')
    axes[0].set_ylabel('Power (W)')
    axes[0].legend(loc='upper right')
    axes[0].grid(True, alpha=0.3)

    # Error plot
    errors = y_true[:n] - y_pred[:n]
    axes[1].bar(range(n), errors, color=np.where(errors > 0, '#4CAF50', '#F44336'), alpha=0.6, width=1.0)
    axes[1].axhline(y=0, color='black', lw=0.5)
    axes[1].set_title('Prediction Error (Actual - Predicted)', fontsize=12)
    axes[1].set_xlabel('Sample')
    axes[1].set_ylabel('Error (W)')
    axes[1].grid(True, alpha=0.3)

    plt.tight_layout()
    out = os.path.join(MODEL_DIR, 'predictions.png')
    plt.savefig(out, dpi=150, bbox_inches='tight')
    plt.close()
    print(f"✓ Predictions plot → {out}")


# ==================== SAVE METADATA ====================

def save_metadata(metrics, df_shape, training_time_str):
    """Save model metadata for the Flask prediction server."""
    metadata = {
        'model_version': '3.0',
        'model_file': 'best_model.keras',
        'scaler_file': 'scaler.pkl',
        'target_column': TARGET_COL,
        'feature_columns': FEATURE_COLS,
        'sequence_length': SEQUENCE_LENGTH,
        'horizons': HORIZONS,
        'primary_horizon': PRIMARY_HORIZON,
        'training_metrics': {
            'mae_watts': round(metrics['mae'], 4),
            'rmse_watts': round(metrics['rmse'], 4),
            'mape_percent': round(metrics['mape'], 2),
        },
        'data_info': {
            'total_rows': df_shape[0],
            'features': df_shape[1],
            'train_ratio': TRAIN_RATIO,
            'val_ratio': VAL_RATIO,
        },
        'training_date': training_time_str,
        'lstm_units': [LSTM_UNITS_1, LSTM_UNITS_2],
        'batch_size': BATCH_SIZE,
        'smooth_window': SMOOTH_WINDOW,
    }

    with open(METADATA_FILE, 'w') as f:
        json.dump(metadata, f, indent=2)
    print(f"✓ Model metadata → {METADATA_FILE}")


# ==================== MAIN ====================

def main():
    print("\n" + "=" * 55)
    print("  Smart Microgrid — Load Prediction v3 (Production)")
    print("=" * 55)

    from datetime import datetime
    train_start = datetime.now()

    # 1. Load
    df = load_csv()
    if df is None:
        return

    # 2. Clean
    df = remove_outliers(df)
    df = smooth_sensor_noise(df)

    # 3. Preprocess
    df_processed = preprocess(df)
    if df_processed is None:
        return

    # 4. Scale
    scaler = MinMaxScaler()
    scaled = scaler.fit_transform(df_processed.values).astype(np.float32)
    target_idx = list(df_processed.columns).index(TARGET_COL)

    # 5. Sequences — primary horizon (1-min ahead)
    horizon_rows = HORIZONS[PRIMARY_HORIZON]
    # If dataset is small, use horizon=1 (next step) as fallback
    if horizon_rows >= len(scaled) - SEQUENCE_LENGTH:
        print(f"⚠  Dataset too small for {PRIMARY_HORIZON} horizon. "
              f"Using next-step prediction.")
        horizon_rows = 1

    X, y = make_sequences(scaled, target_idx, SEQUENCE_LENGTH, horizon_rows)
    print(f"✓ Sequences: X={X.shape}, y={y.shape}  "
          f"(horizon={horizon_rows} rows = "
          f"{horizon_rows * 0.5:.0f}s ahead)")

    # 6. Time-based split
    n = len(X)
    n_train = int(n * TRAIN_RATIO)
    n_val   = int(n * VAL_RATIO)

    X_tr,  y_tr  = X[:n_train],                y[:n_train]
    X_val, y_val = X[n_train:n_train + n_val],  y[n_train:n_train + n_val]
    X_te,  y_te  = X[n_train + n_val:],         y[n_train + n_val:]

    print(f"\nTime-based split:")
    print(f"  Train : {len(X_tr):>7,} samples")
    print(f"  Val   : {len(X_val):>7,} samples")
    print(f"  Test  : {len(X_te):>7,} samples")

    # 7. Build & train
    model = build_model(SEQUENCE_LENGTH, len(FEATURE_COLS))
    history = train(model, X_tr, y_tr, X_val, y_val)

    # 8. Plots
    plot_history(history)

    # 9. Evaluate
    y_true, y_pred, metrics = evaluate(
        model, X_te, y_te, scaler, target_idx, len(FEATURE_COLS)
    )
    plot_predictions(y_true, y_pred)

    # 10. Save scaler
    with open(SCALER_FILE, 'wb') as f:
        pickle.dump(scaler, f)
    print(f"✓ Scaler → {SCALER_FILE}")
    print(f"✓ Best model → {MODEL_FILE}")

    # 11. Save metadata for prediction server
    train_end = datetime.now()
    save_metadata(metrics, df_processed.shape, train_end.isoformat())

    elapsed = (train_end - train_start).total_seconds()
    print(f"\n{'='*55}")
    print(f"  Training Complete!  ({elapsed:.0f}s)")
    print(f"{'='*55}")
    print(f"  Next step:  python predict_server.py")
    print(f"{'='*55}\n")


if __name__ == "__main__":
    main()
